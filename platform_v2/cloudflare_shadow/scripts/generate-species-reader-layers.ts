import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import {
  buildSpeciesReaderGenerationPrompt,
  invasiveCategoryForSpecies,
  normalizeSpeciesReaderKey,
  validateSpeciesReaderOutput,
  type SpeciesReaderAggregateInput,
  type SpeciesReaderGeneratedJson,
} from "../src/speciesReaderLayer";
import { resolveRecordReaderGroup } from "../src/recordReaderModes";

export type GeneratedSpeciesLayerEntry = {
  speciesKey: string;
  canonicalName: string;
  scientificName: string | null;
  taxonGroup: string;
  invasiveCategory: string | null;
  status: "approved_candidate" | "rejected";
  reasons: string[];
  model: string;
  promptTokens: number;
  outputTokens: number;
  output: SpeciesReaderGeneratedJson | null;
};

export type AiInvokeResult = {
  model: string;
  promptTokens: number;
  outputTokens: number;
  parsed: Partial<SpeciesReaderGeneratedJson>;
};

const sqlText = (value: string | null | undefined): string =>
  value === null || value === undefined
    ? "NULL"
    : `'${String(value).replace(/\u0000/gu, "").replace(/'/gu, "''")}'`;

async function callGeminiSingleSpecies(
  apiKey: string,
  input: SpeciesReaderAggregateInput
): Promise<AiInvokeResult> {
  const model = "gemini-2.5-flash";
  const prompt = buildSpeciesReaderGenerationPrompt(input);
  const res = await fetch(
    `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${encodeURIComponent(apiKey)}`,
    {
      method: "POST",
      headers: { "content-type": "application/json" },
      signal: AbortSignal.timeout(15_000),
      body: JSON.stringify({
        contents: [{ parts: [{ text: prompt }] }],
        generationConfig: {
          responseMimeType: "application/json",
          temperature: 0.2,
          maxOutputTokens: 1024,
        },
      }),
    }
  );
  if (!res.ok) throw new Error(`gemini_http_${res.status}`);
  const data = (await res.json()) as {
    candidates?: Array<{ content?: { parts?: Array<{ text?: string }> } }>;
    usageMetadata?: { promptTokenCount?: number; candidatesTokenCount?: number };
  };
  const rawText = data.candidates?.[0]?.content?.parts?.[0]?.text ?? "{}";
  const parsed = JSON.parse(rawText) as Partial<SpeciesReaderGeneratedJson>;
  return {
    model,
    promptTokens: Number(data.usageMetadata?.promptTokenCount ?? 0),
    outputTokens: Number(data.usageMetadata?.candidatesTokenCount ?? 0),
    parsed,
  };
}

export function renderReviewSql(entries: readonly GeneratedSpeciesLayerEntry[]): string {
  const header = [
    "-- Generated by scripts/generate-species-reader-layers.ts",
    "-- Initial review_status is 'pending_review'; commander reviews output and promotes to 'approved' manually.",
  ];
  const rows = entries
    .filter((entry) => entry.status === "approved_candidate" && entry.output)
    .map((entry) => {
      const out = entry.output!;
      return `INSERT OR IGNORE INTO species_reader_layers (species_key, canonical_name, scientific_name, taxon_group, invasive_category, child_text, parent_text, teacher_text, review_status, validation_flags_json, model_name, prompt_tokens, output_tokens) VALUES (${sqlText(entry.speciesKey)}, ${sqlText(entry.canonicalName)}, ${sqlText(entry.scientificName)}, ${sqlText(entry.taxonGroup)}, ${sqlText(entry.invasiveCategory)}, ${sqlText(out.childText)}, ${sqlText(out.parentText)}, ${sqlText(out.teacherText)}, 'pending_review', '[]', ${sqlText(entry.model)}, ${entry.promptTokens}, ${entry.outputTokens});`;
    });
  return [...header, ...rows].join("\n") + "\n";
}

export async function generateSpeciesReaderLayerBatch(
  speciesList: readonly SpeciesReaderAggregateInput[],
  options: {
    dryRun?: boolean;
    limit?: number;
    outJsonPath?: string;
    outSqlPath?: string;
    apiKey?: string;
    invokeAi?: (input: SpeciesReaderAggregateInput) => Promise<AiInvokeResult>;
  } = {}
): Promise<{
  dryRun: boolean;
  entries: GeneratedSpeciesLayerEntry[];
  approvedCount: number;
  rejectedCount: number;
}> {
  const limit = options.limit ?? 25;
  const targets = speciesList.slice(0, Math.max(0, limit));
  const invoker =
    options.invokeAi ??
    (options.apiKey ? (input: SpeciesReaderAggregateInput) => callGeminiSingleSpecies(options.apiKey!, input) : null);
  if (!invoker) {
    throw new Error("gemini_api_key_or_invokeAi_required");
  }

  const entries: GeneratedSpeciesLayerEntry[] = [];
  for (const item of targets) {
    const canonicalName = normalizeSpeciesReaderKey(item.speciesName);
    const ai = await invoker(item);
    const validation = validateSpeciesReaderOutput({
      expectedSpecies: canonicalName,
      output: ai.parsed,
    });
    entries.push({
      speciesKey: canonicalName,
      canonicalName,
      scientificName: item.scientificName ?? null,
      taxonGroup: resolveRecordReaderGroup({
        taxonName: canonicalName,
        taxonOrder: item.taxonomy?.order,
        taxonClass: item.taxonomy?.class,
        taxonKingdom: item.taxonomy?.kingdom,
      }),
      invasiveCategory: invasiveCategoryForSpecies(canonicalName),
      status: validation.valid ? "approved_candidate" : "rejected",
      reasons: validation.reasons,
      model: ai.model,
      promptTokens: ai.promptTokens,
      outputTokens: ai.outputTokens,
      output: validation.valid
        ? {
            speciesName: canonicalName,
            childText: ai.parsed.childText!.trim(),
            parentText: ai.parsed.parentText!.trim(),
            teacherText: ai.parsed.teacherText!.trim(),
          }
        : null,
    });
  }

  const approvedCount = entries.filter((e) => e.status === "approved_candidate").length;
  const rejectedCount = entries.length - approvedCount;

  if (options.outJsonPath) {
    mkdirSync(dirname(options.outJsonPath), { recursive: true });
    writeFileSync(
      options.outJsonPath,
      `${JSON.stringify({ dryRun: options.dryRun !== false, approvedCount, rejectedCount, entries }, null, 2)}\n`
    );
  }
  if (options.outSqlPath) {
    mkdirSync(dirname(options.outSqlPath), { recursive: true });
    writeFileSync(options.outSqlPath, renderReviewSql(entries));
  }

  return { dryRun: options.dryRun !== false, entries, approvedCount, rejectedCount };
}

function parseArgs(argv: string[]) {
  const args = {
    dryRun: true,
    limit: 25,
    input: "",
    outJson: "tmp/species-reader-layers.dry-run.json",
    outSql: "tmp/species-reader-layers.review.sql",
  };
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === "--dry-run") args.dryRun = true;
    else if (a === "--limit") args.limit = Number(argv[++i] ?? 25);
    else if (a === "--input") args.input = argv[++i] ?? "";
    else if (a === "--out-json") args.outJson = argv[++i] ?? args.outJson;
    else if (a === "--out-sql") args.outSql = argv[++i] ?? args.outSql;
  }
  return args;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = parseArgs(process.argv.slice(2));
  if (!args.input || !existsSync(resolve(args.input))) {
    console.error("Usage: npx tsx scripts/generate-species-reader-layers.ts --dry-run --input <species-aggregates.json> [--out-json ...] [--out-sql ...]");
    process.exit(1);
  }
  const speciesList = JSON.parse(readFileSync(resolve(args.input), "utf8")) as SpeciesReaderAggregateInput[];
  generateSpeciesReaderLayerBatch(speciesList, {
    dryRun: true,
    limit: args.limit,
    outJsonPath: resolve(args.outJson),
    outSqlPath: resolve(args.outSql),
    apiKey: process.env.GEMINI_API_KEY,
  }).then(
    (res) => console.log(JSON.stringify({ dryRun: res.dryRun, approvedCount: res.approvedCount, rejectedCount: res.rejectedCount })),
    (err) => {
      console.error(err instanceof Error ? err.message : String(err));
      process.exit(1);
    }
  );
}
